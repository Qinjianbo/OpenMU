    /// <summary>
    /// Fills missing translations and corrects known legacy translations of built-in items.
    /// </summary>
    /// <param name="configuration">The game configuration to update.</param>
    public static void Apply(GameConfiguration configuration)
    {
        foreach (var item in configuration.Items)
        {
            if (!Names.TryGetValue((item.Group, item.Number, item.Name.ValueInNeutralLanguage), out var names))
            {
                continue;
            }

            var current = item.Name.GetTranslation(Chinese, fallbackToNeutral: false);
            if (current != names.Chinese
                && (string.IsNullOrEmpty(current) || current == names.Legacy || current == item.Name.ValueInNeutralLanguage))
            {
                item.Name = item.Name.WithTranslation(Chinese, names.Chinese);
            }
        }
    }
