    /// <param name="name">The neutral name.</param>
    /// <returns>The resource value, or the unchanged name if it is outside the catalog.</returns>
    internal static LocalizedString GetOptionName(LocalizedString name) => Resolve(name, ItemOptionNames.ResourceManager, OptionLookup);

    /// <summary>Resolves a generated item name during initialization.</summary>
    /// <param name="name">The neutral name.</param>
    /// <returns>The complete resource value.</returns>
    internal static LocalizedString GetItemName(LocalizedString name) => Resolve(name, ItemNames.ResourceManager, ItemLookup);

    /// <summary>Resolves a built-in option type during initialization.</summary>
    /// <param name="name">The neutral name.</param>
    /// <returns>The complete resource value.</returns>
    internal static LocalizedString GetOptionTypeName(LocalizedString name) => Resolve(name, ItemOptionTypeNames.ResourceManager, OptionTypeLookup);

    /// <summary>Resolves a built-in option description during initialization.</summary>
    /// <param name="description">The neutral description.</param>
    /// <returns>The complete resource value.</returns>
    internal static LocalizedString GetOptionDescription(LocalizedString description) => Resolve(description, ItemOptionDescriptions.ResourceManager, DescriptionLookup);

    /// <summary>Fills missing item translations without changing customized names or item identities.</summary>
    /// <param name="configuration">The configuration to update.</param>
    internal static void ApplyItems(GameConfiguration configuration)
    {
        var keys = ItemMappings.ToDictionary(m => (m.Group, m.Number), m => m.Key);
        foreach (var item in configuration.Items)
        {
            if (keys.TryGetValue((item.Group, item.Number), out var key))
            {
                item.Name = ConfigurationNameTranslations.CompleteTranslations(item.Name, ItemNames.ResourceManager, key);
            }
        }
    }

    /// <summary>Fills missing option and set translations using the same resources as initialization.</summary>
    /// <param name="configuration">The configuration to update.</param>
    internal static void ApplyOptions(GameConfiguration configuration)
    {
        foreach (var type in configuration.ItemOptionTypes)
        {
            type.Name = Complete(type.Name, ItemOptionTypeNames.ResourceManager, OptionTypeLookup);
            type.Description = Complete(type.Description, ItemOptionDescriptions.ResourceManager, DescriptionLookup);
        }

        foreach (var option in configuration.ItemOptions)
        {
            option.Name = Complete(option.Name, ItemOptionNames.ResourceManager, OptionLookup);
        }

        foreach (var set in configuration.ItemSetGroups)
        {
            set.Name = Complete(set.Name, ItemSetNames.ResourceManager, SetLookup);
        }
    }

    private static IReadOnlyDictionary<string, string> CreateLookup(ResourceManager resources, IReadOnlyList<string> keys) =>
        keys.ToDictionary(key => resources.GetLocalizedString(key).ValueInNeutralLanguage, key => key, StringComparer.Ordinal);

    private static LocalizedString Resolve(LocalizedString name, ResourceManager resources, IReadOnlyDictionary<string, string> lookup) =>
        lookup.TryGetValue(name.ValueInNeutralLanguage, out var key) ? resources.GetLocalizedString(key) : name;

    private static LocalizedString Complete(LocalizedString name, ResourceManager resources, IReadOnlyDictionary<string, string> lookup) =>
        lookup.TryGetValue(name.ValueInNeutralLanguage, out var key) ? ConfigurationNameTranslations.CompleteTranslations(name, resources, key) : name;
}
